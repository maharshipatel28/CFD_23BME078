import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# 1. PARAMETERS
# ============================================================

L = 1.0
H = 1.0

NX = 101
NY = 101

ALPHA = 1.0
FO = 0.24

T_INITIAL = 0.0
T_LEFT = 100.0
T_TOP = 0.0
T_BOTTOM = 0.0

MAX_ITER = 200000
TOL = 1e-7

# ============================================================
# 2. GRID
# ============================================================

x = np.linspace(0, L, NX)
y = np.linspace(0, H, NY)
dx = x[1] - x[0]
dy = y[1] - y[0]

if not np.isclose(dx, dy):
    raise ValueError("This code requires dx = dy.")

if not (0 < FO <= 0.25):
    raise ValueError("For explicit diffusion, use 0 < FO <= 0.25.")

dt = FO * dx**2 / ALPHA
X, Y = np.meshgrid(x, y)

print("2D HEAT CONDUCTION")
print("-" * 40)
print(f"Grid: {NX} x {NY}")
print(f"dx = dy = {dx:.5f} m")
print(f"Fourier number = {FO}")
print(f"Time step = {dt:.6e} s")
print(f"Tolerance = {TOL:.1e}")


# ============================================================
# 3. BOUNDARY CONDITIONS
# ============================================================

def apply_boundary(T):
    # Left boundary
    T[:, 0] = T_LEFT

    # Insulated right boundary: zero normal temperature gradient
    T[:, -1] = T[:, -2]

    # Top and bottom boundaries
    T[0, :] = T_BOTTOM
    T[-1, :] = T_TOP

    # Corner temperatures follow the top and bottom walls
    T[0, 0] = T_BOTTOM
    T[-1, 0] = T_TOP
    T[0, -1] = T_BOTTOM
    T[-1, -1] = T_TOP

    return T


def initialize():
    return apply_boundary(np.full((NY, NX), T_INITIAL, dtype=float))


# ============================================================
# 4. EXPLICIT METHOD
# ============================================================

def explicit_solution():
    T = initialize()

    for n in range(1, MAX_ITER + 1):
        old = T.copy()

        T[1:-1, 1:-1] = old[1:-1, 1:-1] + FO * (
            old[1:-1, 2:]
            + old[1:-1, :-2]
            + old[2:, 1:-1]
            + old[:-2, 1:-1]
            - 4.0 * old[1:-1, 1:-1]
        )

        apply_boundary(T)

        error = np.max(np.abs(T - old))

        if error < TOL:
            return T, n, error, True

    return T, MAX_ITER, error, False


# ============================================================
# 5. IMPLICIT METHOD: GAUSS-SEIDEL ITERATION
# Solves the steady Laplace equation iteratively.
# ============================================================

def implicit_solution():
    T = initialize()

    for n in range(1, MAX_ITER + 1):
        old = T.copy()

        # In-place updates implement Gauss-Seidel iteration.
        # The insulated right boundary is handled separately.
        for j in range(1, NY - 1):
            for i in range(1, NX - 1):
                if i == NX - 2:
                    # Right neighbor equals the current cell
                    T[j, i] = (
                        T[j, i - 1]
                        + T[j - 1, i]
                        + T[j + 1, i]
                    ) / 3.0
                else:
                    T[j, i] = 0.25 * (
                        T[j, i - 1]
                        + T[j, i + 1]
                        + T[j - 1, i]
                        + T[j + 1, i]
                    )

        apply_boundary(T)

        error = np.max(np.abs(T - old))

        if error < TOL:
            return T, n, error, True

    return T, MAX_ITER, error, False


# ============================================================
# 6. RUN BOTH SOLVERS
# ============================================================

T_exp, n_exp, err_exp, conv_exp = explicit_solution()
T_imp, n_imp, err_imp, conv_imp = implicit_solution()

for name, n, err, conv in [
    ("Explicit", n_exp, err_exp, conv_exp),
    ("Implicit (Gauss-Seidel)", n_imp, err_imp, conv_imp)
]:
    print(f"\n{name}")
    print(f"Status: {'Converged' if conv else 'Maximum iterations reached'}")
    print(f"Iterations: {n}")
    print(f"Final maximum change: {err:.4e} deg C")


# ============================================================
# 7. PLOT: REFERENCE-STYLE SIDE-BY-SIDE CONTOURS
# ============================================================

levels = np.linspace(0, 100, 8)

fig, axes = plt.subplots(1, 2, figsize=(14, 6))

plot_data = [
    (axes[0], T_exp, "Explicit Solution", n_exp, conv_exp),
    (axes[1], T_imp, "Implicit Solution (Gauss-Seidel)", n_imp, conv_imp)
]

for ax, T, title, iterations, converged in plot_data:
    contour = ax.contourf(
        X, Y, T,
        levels=levels,
        cmap="seismic",
        vmin=0,
        vmax=100
    )

    ax.set_xlabel("X")
    ax.set_ylabel("Y")
    status = "converged" if converged else "not converged"
    ax.set_title(f"{title} ({status} at n={iterations})")
    ax.set_aspect("equal")

    cbar = fig.colorbar(contour, ax=ax)
    cbar.set_label("Temperature (°C)")
    cbar.set_ticks(np.linspace(0, 100, 8))

plt.tight_layout()
plt.show()


# ============================================================
# 8. OPTIONAL: COMPARE TEMPERATURE FIELDS
# ============================================================

plt.figure(figsize=(7, 6))

difference = np.abs(T_exp - T_imp)

plt.contourf(X, Y, difference, levels=20, cmap="viridis")
plt.colorbar(label="Absolute temperature difference (°C)")
plt.xlabel("X")
plt.ylabel("Y")
plt.title("Difference Between Explicit and Implicit Solutions")
plt.gca().set_aspect("equal")
plt.tight_layout()
plt.show()

print("\nAll calculations and plots completed.")