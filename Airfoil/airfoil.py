# ================================================================
# NACA 0012 AIRFOIL CFD — Re = 1000
# Immersed Boundary / Volume Penalization Method
# Outputs: CL-AoA, CD-AoA, velocity, pressure and vorticity
# Educational 2D incompressible flow solver
# ================================================================

import numpy as np
import matplotlib.pyplot as plt

# ================================================================
# 1. USER-CHANGEABLE PARAMETERS
# ================================================================

c = 1.0                  # Airfoil chord (reference length)
Lx, Ly = 6.0, 3.0       # Domain dimensions in chord lengths
nx, ny = 300, 120        # Grid points; increase for mesh verification

Re = 1000.0              # Reynolds number = U*c/nu
U = 1.0                  # Inlet velocity
Co = 0.10                # Courant number for time-step selection
nit = 12000              # Steps per angle of attack
eta_factor = 1.0         # Penalty time scale multiplier
alpha_p = 1.0            # Pressure correction relaxation
tk = 0.12                # NACA 0012 thickness ratio
tol_cl = 1e-4             # Optional diagnostic tolerance (not a stop rule)

aoa_list = [0, 5, 10, 15, 20]  # Angle of attack in degrees

xle = Lx / 4.0           # Leading-edge x position
Cy = Ly / 2.0            # Airfoil reference centerline

# ================================================================
# 2. GRID AND TIME STEP
# ================================================================

if min(nx, ny) < 5 or min(c, Lx, Ly, U, Re) <= 0:
    raise ValueError("Grid and physical parameters must be positive.")

dx = Lx / nx
dy = Ly / ny
nu = U * c / Re

dt_conv = Co * min(dx, dy) / U
dt_diff = 0.45 / (
    2.0 * nu * (1.0 / dx**2 + 1.0 / dy**2)
)
dt = min(dt_conv, dt_diff)
eta = max(eta_factor * dt, 1e-8)

x = np.arange(nx) * dx
y = np.arange(ny) * dy
X, Y = np.meshgrid(x, y)

print("=" * 55)
print(f"Reynolds number : {Re:g}")
print(f"Grid            : {nx} x {ny}")
print(f"dx, dy          : {dx:.5f}, {dy:.5f}")
print(f"Time step       : {dt:.6e}")
print(f"Penalty eta     : {eta:.6e}")
print(f"Time per angle  : {nit * dt:.3f} (c/U)")
print("=" * 55)

# ================================================================
# 3. PRESSURE-CORRECTION POISSON SOLVER
# ================================================================

# Solve the discrete pressure-correction Poisson equation
# using an eigen-decomposition of the Cartesian Laplacian.

ni, nj = ny - 2, nx - 2

Ax = (
    np.diag(-2.0 * np.ones(nj))
    + np.diag(np.ones(nj - 1), 1)
    + np.diag(np.ones(nj - 1), -1)
) / dx**2

# Approximate zero-gradient correction at the inlet
Ax[0, 0] = -1.0 / dx**2

Ay = (
    np.diag(-2.0 * np.ones(ni))
    + np.diag(np.ones(ni - 1), 1)
    + np.diag(np.ones(ni - 1), -1)
) / dy**2

# Zero-gradient correction at top and bottom
Ay[0, 0] = -1.0 / dy**2
Ay[-1, -1] = -1.0 / dy**2

ly, Qy = np.linalg.eigh(Ay)
lx, Qx = np.linalg.eigh(Ax)
den = ly[:, None] + lx[None, :]

if np.any(np.abs(den) < 1e-12):
    raise ValueError("Pressure solver has a near-zero eigenvalue.")

def pressure_solve(rhs):
    pc = np.zeros((ny, nx))

    transformed = Qy.T @ rhs[1:-1, 1:-1] @ Qx
    pc[1:-1, 1:-1] = Qy @ (transformed / den) @ Qx.T

    pc[:, 0] = pc[:, 1]
    pc[0, :] = pc[1, :]
    pc[-1, :] = pc[-2, :]
    pc[:, -1] = 0.0

    return pc

# ================================================================
# 4. BOUNDARY CONDITIONS
# ================================================================

def apply_boundary(u, v):
    # Inlet: uniform horizontal flow
    u[:, 0] = U
    v[:, 0] = 0.0

    # Outlet: approximate zero-gradient condition
    u[:, -1] = u[:, -2]
    v[:, -1] = v[:, -2]

    # Top and bottom: symmetry/slip boundaries
    u[0, :] = u[1, :]
    v[0, :] = 0.0
    u[-1, :] = u[-2, :]
    v[-1, :] = 0.0

# ================================================================
# 5. NACA 0012 AIRFOIL MASK
# ================================================================

def make_airfoil_mask(angle_deg):
    angle = np.deg2rad(angle_deg)

    # Inverse rotation into airfoil coordinates.
    # Positive AoA rotates the chord counterclockwise.
    xp = X - xle
    yp = Y - Cy

    xb = xp * np.cos(angle) + yp * np.sin(angle)
    yb = -xp * np.sin(angle) + yp * np.cos(angle)

    xc = np.clip(xb / c, 0.0, 1.0)

    # Standard NACA 00xx half-thickness distribution
    yt = 5.0 * tk * c * (
        0.2969 * np.sqrt(xc)
        - 0.1260 * xc
        - 0.3516 * xc**2
        + 0.2843 * xc**3
        - 0.1036 * xc**4
    )

    mask = (
        (xb >= 0.0)
        & (xb <= c)
        & (np.abs(yb) <= yt)
    )

    # Binary mask: 1 inside the airfoil, 0 outside.
    # This is a simple volume-penalization approximation.
    alpha = mask.astype(float)

    return alpha, mask

# ================================================================
# 6. INITIAL CONDITIONS
# ================================================================

u = np.full((ny, nx), U, dtype=float)
v = np.zeros((ny, nx), dtype=float)
p = np.zeros((ny, nx), dtype=float)

Cl_mean_list = []
Cd_mean_list = []

last_mask = np.zeros((ny, nx), dtype=bool)

# ================================================================
# 7. SOLVE FLOW AT EACH ANGLE OF ATTACK
# ================================================================

for aoa_deg in aoa_list:

    print(f"\nStarting angle of attack: {aoa_deg} degrees")

    alpha, mask = make_airfoil_mask(aoa_deg)
    last_mask = mask.copy()

    # Use the previous angle solution as the next initial guess
    u[mask] = 0.0
    v[mask] = 0.0

    Cl_hist = np.zeros(nit)
    Cd_hist = np.zeros(nit)
    residual = np.inf

    for n in range(nit):

        apply_boundary(u, v)

        u0 = u.copy()
        v0 = v.copy()
        p0 = p.copy()

        ui = u0[1:-1, 1:-1]
        vi = v0[1:-1, 1:-1]

        # --------------------------------------------------------
        # 7A. UPWIND CONVECTION
        # --------------------------------------------------------

        def convection(q):
            # Every derivative has shape (ny-2, nx-2).
            q_c = q[1:-1, 1:-1]

            qx_b = (q_c - q[1:-1, :-2]) / dx
            qx_f = (q[1:-1, 2:] - q_c) / dx

            qy_b = (q_c - q[:-2, 1:-1]) / dy
            qy_f = (q[2:, 1:-1] - q_c) / dy

            return (
                np.maximum(ui, 0.0) * qx_b
                + np.minimum(ui, 0.0) * qx_f
                + np.maximum(vi, 0.0) * qy_b
                + np.minimum(vi, 0.0) * qy_f
            )

        conv_u = convection(u0)
        conv_v = convection(v0)

        # --------------------------------------------------------
        # 7B. VISCOUS DIFFUSION
        # --------------------------------------------------------

        lap_u = (
            (u0[1:-1, 2:] - 2.0*ui + u0[1:-1, :-2]) / dx**2
            + (u0[2:, 1:-1] - 2.0*ui + u0[:-2, 1:-1]) / dy**2
        )

        lap_v = (
            (v0[1:-1, 2:] - 2.0*vi + v0[1:-1, :-2]) / dx**2
            + (v0[2:, 1:-1] - 2.0*vi + v0[:-2, 1:-1]) / dy**2
        )

        # Pressure gradients
        dpdx = (p0[1:-1, 2:] - p0[1:-1, :-2]) / (2.0*dx)
        dpdy = (p0[2:, 1:-1] - p0[:-2, 1:-1]) / (2.0*dy)

        # Implicit penalty contribution
        a = alpha[1:-1, 1:-1]
        penalty_den = 1.0 + dt * a / eta

        # Predictor velocities
        u[1:-1, 1:-1] = (
            ui + dt * (-conv_u + nu*lap_u - dpdx)
        ) / penalty_den

        v[1:-1, 1:-1] = (
            vi + dt * (-conv_v + nu*lap_v - dpdy)
        ) / penalty_den

        apply_boundary(u, v)

        # --------------------------------------------------------
        # 7C. PRESSURE CORRECTION
        # --------------------------------------------------------

        div = np.zeros_like(u)

        div[1:-1, 1:-1] = (
            (u[1:-1, 2:] - u[1:-1, :-2]) / (2.0*dx)
            + (v[2:, 1:-1] - v[:-2, 1:-1]) / (2.0*dy)
        )

        pc = pressure_solve(div / dt)

        # Correct velocity
        u[1:-1, 1:-1] -= (
            dt * (pc[1:-1, 2:] - pc[1:-1, :-2]) / (2.0*dx)
        )

        v[1:-1, 1:-1] -= (
            dt * (pc[2:, 1:-1] - pc[:-2, 1:-1]) / (2.0*dy)
        )

        # Update pressure
        p = p0 + alpha_p * pc

        apply_boundary(u, v)

        # --------------------------------------------------------
        # 7D. QUALITATIVE FORCE COEFFICIENTS
        # --------------------------------------------------------

        # Reaction of the solid to the volume-penalty force.
        # These are approximate force estimates, not validated
        # surface-integrated aerodynamic coefficients.
        Fx = np.sum(alpha * u) / eta * dx * dy
        Fy = np.sum(alpha * v) / eta * dx * dy

        Cd_hist[n] = 2.0 * Fx / (U**2 * c)
        Cl_hist[n] = 2.0 * Fy / (U**2 * c)

        # Fluid-only velocity update residual
        fluid = ~mask
        residual = max(
            np.max(np.abs(u - u0)[fluid]),
            np.max(np.abs(v - v0)[fluid])
        ) / dt

        if n % 500 == 0:
            print(
                f"AoA={aoa_deg:2d} deg | step={n:5d} | "
                f"res={residual:.3e} | "
                f"CL={Cl_hist[n]:.5f} | CD={Cd_hist[n]:.5f}"
            )

    # Discard the first half of the signal as startup transient.
    # This is a fixed-duration run, not a steady-state guarantee.
    start = nit // 2

    Cl_avg = float(np.mean(Cl_hist[start:]))
    Cd_avg = float(np.mean(Cd_hist[start:]))

    Cl_mean_list.append(Cl_avg)
    Cd_mean_list.append(Cd_avg)

    print(
        f"Finished AoA={aoa_deg} deg | "
        f"mean CL={Cl_avg:.5f} | mean CD={Cd_avg:.5f} | "
        f"final residual={residual:.3e}"
    )

# ================================================================
# 8. CL VS ANGLE OF ATTACK
# ================================================================

angles = np.asarray(aoa_list)

plt.figure(figsize=(8, 5))
plt.plot(angles, Cl_mean_list, "o-", linewidth=2)
plt.xlabel("Angle of attack (degrees)")
plt.ylabel("Mean lift coefficient, CL")
plt.title(f"CL vs angle of attack, Re = {Re:g}")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# ================================================================
# 9. CD VS ANGLE OF ATTACK
# ================================================================

plt.figure(figsize=(8, 5))
plt.plot(angles, Cd_mean_list, "s-", linewidth=2)
plt.xlabel("Angle of attack (degrees)")
plt.ylabel("Mean drag coefficient, CD")
plt.title(f"CD vs angle of attack, Re = {Re:g}")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# ================================================================
# 10. VELOCITY MAGNITUDE CONTOUR
# ================================================================

speed = np.sqrt(u**2 + v**2)
speed_plot = np.ma.masked_where(last_mask, speed)

plt.figure(figsize=(13, 4))
plt.contourf(X, Y, speed_plot, levels=40, cmap="jet")
plt.colorbar(label="Velocity magnitude / U")
plt.title(f"Velocity magnitude at AoA={aoa_list[-1]} degrees")
plt.xlabel("x / c")
plt.ylabel("y / c")
plt.gca().set_aspect("equal", adjustable="box")
plt.tight_layout()
plt.show()

# ================================================================
# 11. PRESSURE CONTOUR
# ================================================================

p_plot = np.ma.masked_where(last_mask, p)

plt.figure(figsize=(13, 4))
plt.contourf(X, Y, p_plot, levels=40, cmap="seismic")
plt.colorbar(label="Nondimensional pressure")
plt.title(f"Pressure field at AoA={aoa_list[-1]} degrees")
plt.xlabel("x / c")
plt.ylabel("y / c")
plt.gca().set_aspect("equal", adjustable="box")
plt.tight_layout()
plt.show()

# ================================================================
# 12. VORTICITY CONTOUR
# ================================================================

vorticity = (
    np.gradient(v, dx, axis=1)
    - np.gradient(u, dy, axis=0)
)
vorticity_plot = np.ma.masked_where(last_mask, vorticity)

vmax = max(
    float(np.percentile(np.abs(vorticity[~last_mask]), 98)),
    1e-8
)

plt.figure(figsize=(13, 4))
plt.contourf(
    X, Y, vorticity_plot,
    levels=np.linspace(-vmax, vmax, 41),
    cmap="seismic", extend="both"
)
plt.colorbar(label="Vorticity")
plt.title(f"Vorticity at AoA={aoa_list[-1]} degrees")
plt.xlabel("x / c")
plt.ylabel("y / c")
plt.gca().set_aspect("equal", adjustable="box")
plt.tight_layout()
plt.show()

# ================================================================
# 13. SUMMARY TABLE
# ================================================================

print("\nFINAL SUMMARY")
print("-" * 43)
print(f"{'AoA (deg)':>10} {'Mean CL':>14} {'Mean CD':>14}")
print("-" * 43)

for angle, cl_value, cd_value in zip(
    aoa_list, Cl_mean_list, Cd_mean_list
):
    print(f"{angle:10.1f} {cl_value:14.6f} {cd_value:14.6f}")

print("-" * 43)
print("Simulation completed.")
print("Check mesh independence, divergence and force convergence")
print("before interpreting these results quantitatively.")