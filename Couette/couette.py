import numpy as np
import matplotlib.pyplot as plt

# ============================================================
# 1. PARAMETERS
# ============================================================

NY = 101
H = 1.0                   # Plate spacing (m)
U_TOP = 1.0               # Upper plate velocity (m/s)
RE = 100.0
T_END = 2.0               # Maximum physical simulation time (s)
TOL = 1e-8
MAX_ITER = 500000

EXPLICIT_FACTOR = 0.40
DT_IMPLICIT = 0.01
DT_CN = 0.01

# ============================================================
# 2. GRID AND FLUID PROPERTIES
# ============================================================

y = np.linspace(0.0, H, NY)
dy = y[1] - y[0]

# Reynolds number: Re = U*H/nu
nu = U_TOP * H / RE

DT_EXPLICIT = EXPLICIT_FACTOR * dy**2 / nu

print("=" * 60)
print("COUETTE FLOW SIMULATION")
print("=" * 60)
print(f"Grid points             : {NY}")
print(f"Plate spacing           : {H} m")
print(f"Top plate velocity      : {U_TOP} m/s")
print(f"Reynolds number         : {RE}")
print(f"Kinematic viscosity     : {nu:.6e} m^2/s")
print(f"Grid spacing            : {dy:.6e} m")
print(f"Explicit time step      : {DT_EXPLICIT:.6e} s")
print(f"Implicit time step      : {DT_IMPLICIT:.6e} s")
print(f"Crank-Nicolson time step: {DT_CN:.6e} s")
print("=" * 60)


# ============================================================
# 3. BOUNDARY CONDITIONS
# ============================================================

def apply_boundary_conditions(u):
    u[0] = 0.0
    u[-1] = U_TOP
    return u


# ============================================================
# 4. TRIDIAGONAL SOLVER: THOMAS ALGORITHM
# ============================================================

def solve_tridiagonal(lower, diagonal, upper, rhs):
    a = np.array(lower, dtype=float, copy=True)
    b = np.array(diagonal, dtype=float, copy=True)
    c = np.array(upper, dtype=float, copy=True)
    d = np.array(rhs, dtype=float, copy=True)

    n = len(b)

    for i in range(1, n):
        if abs(b[i - 1]) < 1e-14:
            raise ZeroDivisionError("Zero pivot in tridiagonal solver.")

        factor = a[i - 1] / b[i - 1]
        b[i] -= factor * c[i - 1]
        d[i] -= factor * d[i - 1]

    if abs(b[-1]) < 1e-14:
        raise ZeroDivisionError("Zero final pivot.")

    solution = np.zeros(n)
    solution[-1] = d[-1] / b[-1]

    for i in range(n - 2, -1, -1):
        solution[i] = (
            d[i] - c[i] * solution[i + 1]
        ) / b[i]

    return solution


# ============================================================
# 5. COUETTE FLOW SOLVER
# ============================================================

def run_solver(method, dt):

    u = np.zeros(NY)
    apply_boundary_conditions(u)

    n = NY - 2
    r = nu * dt / dy**2

    if method == "Explicit" and r > 0.5:
        raise ValueError(
            f"Explicit method unstable: r={r:.4f}. "
            "Reduce the time step."
        )

    if method == "Implicit":
        lower = -r * np.ones(n - 1)
        diagonal = (1.0 + 2.0 * r) * np.ones(n)
        upper = -r * np.ones(n - 1)

    elif method == "Crank-Nicolson":
        lower = -0.5 * r * np.ones(n - 1)
        diagonal = (1.0 + r) * np.ones(n)
        upper = -0.5 * r * np.ones(n - 1)

    elif method != "Explicit":
        raise ValueError("Unknown method.")

    history_time = []
    history_change = []
    time = 0.0
    converged = False

    for iteration in range(1, MAX_ITER + 1):

        old = u.copy()

        if method == "Explicit":

            u[1:-1] = old[1:-1] + r * (
                old[2:] - 2.0 * old[1:-1] + old[:-2]
            )

        elif method == "Implicit":

            rhs = old[1:-1].copy()
            rhs[-1] += r * U_TOP

            u[1:-1] = solve_tridiagonal(
                lower, diagonal, upper, rhs
            )

        elif method == "Crank-Nicolson":

            rhs = (1.0 - r) * old[1:-1] + 0.5 * r * (
                old[2:] + old[:-2]
            )

            # Correct contribution from the moving top wall
            rhs[-1] += r * U_TOP

            u[1:-1] = solve_tridiagonal(
                lower, diagonal, upper, rhs
            )

        apply_boundary_conditions(u)

        time += dt
        change = np.max(np.abs(u - old))

        if iteration == 1 or iteration % 100 == 0:
            history_time.append(time)
            history_change.append(max(change, 1e-16))

        if change < TOL:
            converged = True
            break

        if time >= T_END:
            break

    return {
        "u": u.copy(),
        "time": time,
        "iterations": iteration,
        "change": change,
        "converged": converged,
        "history_time": np.array(history_time),
        "history_change": np.array(history_change),
        "r": r
    }


# ============================================================
# 6. RUN ALL METHODS
# ============================================================

results = {
    "Explicit": run_solver("Explicit", DT_EXPLICIT),
    "Implicit": run_solver("Implicit", DT_IMPLICIT),
    "Crank-Nicolson": run_solver("Crank-Nicolson", DT_CN)
}

# Analytical steady-state solution
u_exact = U_TOP * y / H


# ============================================================
# 7. PRINT SUMMARY
# ============================================================

print("\nSIMULATION RESULTS")
print("-" * 75)

for name, result in results.items():
    error = np.max(np.abs(result["u"] - u_exact))

    print(f"\n{name}")
    print(f"Iterations             : {result['iterations']}")
    print(f"Simulation time        : {result['time']:.6f} s")
    print(f"Diffusion number        : {result['r']:.6f}")
    print(f"Final maximum change   : {result['change']:.6e}")
    print(f"Convergence criterion  : {result['converged']}")
    print(f"Max steady-state error : {error:.6e}")


