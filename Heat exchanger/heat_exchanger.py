import numpy as np
import matplotlib.pyplot as plt

# ==============================================================
# 1. USER PARAMETERS — CHANGE THESE VALUES
# ==============================================================

# Geometry [m]
LENGTH = 30.0
COLD_HEIGHT = 5.0
WALL_THICKNESS = 0.1
HOT_HEIGHT = 5.0

# Grid resolution
NX = 200
NY_COLD = 30
NY_WALL = 3
NY_HOT = 30

# Inlet temperatures [deg C]
T_HOT_IN = 5.0
T_COLD_IN = -5.0

# Material properties
K_WATER = 0.6          # W/(m K)
K_COPPER = 400.0       # W/(m K)
RHO_WATER = 997.0      # kg/m^3
CP_WATER = 4182.0      # J/(kg K)
RHO_COPPER = 8960.0    # kg/m^3
CP_COPPER = 385.0      # J/(kg K)

# Prescribed maximum channel velocities [m/s]
U_HOT_MAX = 0.10
U_COLD_MAX = 0.10

# True: counterflow; False: parallel flow
COUNTERFLOW = True

# Numerical controls
MAX_ITERATIONS = 50000
PRINT_EVERY = 1000
TOLERANCE = 1e-6
SAFETY_FACTOR = 0.40

# ==============================================================
# 2. VALIDATE PARAMETERS AND CREATE A NONUNIFORM GRID
# ==============================================================

if min(LENGTH, COLD_HEIGHT, WALL_THICKNESS, HOT_HEIGHT) <= 0:
    raise ValueError("All geometry dimensions must be positive.")

if min(NX, NY_COLD, NY_WALL, NY_HOT) < 2:
    raise ValueError("Each grid region must contain at least 2 cells.")

if min(K_WATER, K_COPPER, RHO_WATER, CP_WATER,
       RHO_COPPER, CP_COPPER) <= 0:
    raise ValueError("Material properties must be positive.")

if min(U_HOT_MAX, U_COLD_MAX) < 0:
    raise ValueError("Velocities cannot be negative.")

NY = NY_COLD + NY_WALL + NY_HOT
HEIGHT = COLD_HEIGHT + WALL_THICKNESS + HOT_HEIGHT

dx = LENGTH / NX

# Cell faces: every region has its own physical thickness.
y_faces_cold = np.linspace(0, COLD_HEIGHT, NY_COLD + 1)
y_faces_wall = np.linspace(
    COLD_HEIGHT, COLD_HEIGHT + WALL_THICKNESS, NY_WALL + 1
)
y_faces_hot = np.linspace(
    COLD_HEIGHT + WALL_THICKNESS, HEIGHT, NY_HOT + 1
)

y_faces = np.concatenate([
    y_faces_cold,
    y_faces_wall[1:],
    y_faces_hot[1:]
])

# Cell-center coordinates
y = 0.5 * (y_faces[:-1] + y_faces[1:])
x = (np.arange(NX) + 0.5) * dx
X, Y = np.meshgrid(x, y)

dy = np.diff(y_faces)
dy2d = dy[:, None]

cold_rows = slice(0, NY_COLD)
wall_rows = slice(NY_COLD, NY_COLD + NY_WALL)
hot_rows = slice(NY_COLD + NY_WALL, NY)

is_wall = np.zeros(NY, dtype=bool)
is_wall[wall_rows] = True

print("Grid:", NX, "x", NY)
print("dx =", dx, "m")
print("Cold cell height =", dy[cold_rows][0], "m")
print("Copper cell height =", dy[wall_rows][0], "m")
print("Hot cell height =", dy[hot_rows][0], "m")

# ==============================================================
# 3. MATERIAL FIELDS
# ==============================================================

k = np.full(NY, K_WATER)
rho = np.full(NY, RHO_WATER)
cp = np.full(NY, CP_WATER)

k[wall_rows] = K_COPPER
rho[wall_rows] = RHO_COPPER
cp[wall_rows] = CP_COPPER

# Volumetric heat capacity [J/(m^3 K)]
capacity = rho * cp

# ==============================================================
# 4. PRESCRIBED PARABOLIC VELOCITY PROFILES
# ==============================================================

# Flat-plate Poiseuille-shaped profiles:
# u = umax * [1 - (2*y_local/H)^2]
# Maximum velocity is specified directly by the user.

u = np.zeros((NY, NX))
v = np.zeros_like(u)

y_cold_local = y[cold_rows] / COLD_HEIGHT
u[cold_rows, :] = (
    U_COLD_MAX * (1.0 - (2.0*y_cold_local - 1.0)**2)[:, None]
)

y_hot_local = (
    y[hot_rows] - (COLD_HEIGHT + WALL_THICKNESS)
) / HOT_HEIGHT

u[hot_rows, :] = (
    U_HOT_MAX * (1.0 - (2.0*y_hot_local - 1.0)**2)[:, None]
)

if COUNTERFLOW:
    u[cold_rows, :] *= -1.0

# No fluid motion in the copper wall.
u[wall_rows, :] = 0.0

plt.figure(figsize=(10, 4))
plt.pcolormesh(
    x, y, u, shading="nearest", cmap="RdBu_r"
)
plt.colorbar(label="Streamwise velocity u [m/s]")
plt.xlabel("Channel length x [m]")
plt.ylabel("Height y [m]")
plt.title("Prescribed velocity field")
plt.axhspan(
    COLD_HEIGHT, COLD_HEIGHT + WALL_THICKNESS,
    color="gray", alpha=0.7
)
plt.tight_layout()
plt.show()

# ==============================================================
# 5. INITIAL TEMPERATURE FIELD
# ==============================================================

T = np.empty((NY, NX))
T[cold_rows, :] = T_COLD_IN
T[wall_rows, :] = 0.5 * (T_COLD_IN + T_HOT_IN)
T[hot_rows, :] = T_HOT_IN

# ==============================================================
# 6. BOUNDARY CONDITIONS
# ==============================================================

def apply_temperature_bc(A):
    # Inlet and outlet conditions for cold fluid
    if COUNTERFLOW:
        A[cold_rows, -1] = T_COLD_IN
        A[cold_rows, 0] = A[cold_rows, 1]
    else:
        A[cold_rows, 0] = T_COLD_IN
        A[cold_rows, -1] = A[cold_rows, -2]

    # Hot fluid always flows from left to right
    A[hot_rows, 0] = T_HOT_IN
    A[hot_rows, -1] = A[hot_rows, -2]

    # Insulated top and bottom
    A[0, :] = A[1, :]
    A[-1, :] = A[-2, :]

    # Copper wall inlet/outlet: zero axial heat flux
    A[wall_rows, 0] = A[wall_rows, 1]
    A[wall_rows, -1] = A[wall_rows, -2]

# ==============================================================
# 7. FINITE-VOLUME HEAT-FLUX CALCULATION
# ==============================================================

# Harmonic conductivity for adjacent cell centers.
# This gives conductivity-weighted heat flux across interfaces.
k_face_y = (
    (dy[:-1, None] + dy[1:, None])
    / (
        dy[:-1, None] / k[:-1, None]
        + dy[1:, None] / k[1:, None]
    )
)

# Thermal resistance across each vertical cell-center face.
distance_y = 0.5 * (dy[:-1] + dy[1:])

# Explicit transient energy equation used to approach steady state.
# Equation: rho*cp*dT/dt + rho*cp*u*dT/dx = div(k grad T)

def calculate_dt():
    # Conservative explicit diffusion stability estimate.
    alpha = k / capacity
    alpha_max = np.max(alpha)

    dt_diff = 0.20 / (
        alpha_max * (
            2.0 / dx**2 + 2.0 / np.min(dy)**2
        )
    )

    # Advection stability estimate
    umax = max(np.max(np.abs(u)), 1e-12)
    dt_adv = 0.40 * dx / umax

    # Additional interface-conduction stability limit
    # based on local thermal capacity and face conductances.
    conductance_sum = np.zeros(NY)

    conductance_sum[:-1] += k_face_y[:, 0] / distance_y
    conductance_sum[1:] += k_face_y[:, 0] / distance_y

    dt_interface = np.min(
        capacity * dy / np.maximum(conductance_sum, 1e-30)
    ) * 0.40

    return SAFETY_FACTOR * min(dt_diff, dt_adv, dt_interface)

dt = calculate_dt()
print(f"Pseudo-time step = {dt:.4e} s")

def energy_step(A):
    # Axial conduction using local thermal conductivity
    qx_e = K_WATER * 0.0 + k[:, None] * (
        A[:, 1:] - A[:, :-1]
    ) / dx

    diffusion_x = np.zeros_like(A)
    diffusion_x[:, 1:-1] = (
        qx_e[:, 1:] - qx_e[:, :-1]
    ) / dx

    # Vertical conduction: heat flux across every horizontal face.
    qy = k_face_y * (
        A[1:, :] - A[:-1, :]
    ) / distance_y[:, None]

    diffusion_y = np.zeros_like(A)
    diffusion_y[1:-1, :] = (
        qy[1:, :] - qy[:-1, :]
    ) / dy[1:-1, None]

    # Conservative first-order upwind convection.
    # Copper rows have u=0, so there is no fluid advection there.
    convection = np.zeros_like(A)

    pos = u[:, 1:-1] >= 0.0
    neg = ~pos

    dTdx = np.where(
        pos,
        (A[:, 1:-1] - A[:, :-2]) / dx,
        (A[:, 2:] - A[:, 1:-1]) / dx
    )

    convection[:, 1:-1] = (
        rho[:, None] * cp[:, None]
        * u[:, 1:-1] * dTdx
    )

    # Explicit pseudo-time update
    A_new = A.copy()
    A_new[:, :] += dt * (
        diffusion_x + diffusion_y - convection
    ) / capacity[:, None]

    return A_new

# ==============================================================
# 8. ITERATE TO A STEADY TEMPERATURE FIELD
# ==============================================================

apply_temperature_bc(T)

converged = False
error = np.inf

for it in range(MAX_ITERATIONS):
    T_old = T.copy()

    T = energy_step(T)
    apply_temperature_bc(T)

    error = np.max(np.abs(T - T_old))

    if it % PRINT_EVERY == 0:
        print(f"Iteration {it:6d}: max temperature change = {error:.3e} K")

    if error < TOLERANCE:
        converged = True
        print(
            f"Converged at iteration {it + 1}, "
            f"change = {error:.3e} K"
        )
        break

if not converged:
    print(
        "Maximum iterations reached. The solution may need more "
        "iterations or improved numerical treatment."
    )

# ==============================================================
# 9. FINAL TEMPERATURE CONTOUR
# ==============================================================

plt.figure(figsize=(13, 5))

mesh = plt.pcolormesh(
    x, y, T,
    shading="nearest",
    cmap="RdBu_r"
)

plt.colorbar(mesh, label="Temperature [deg C]")

plt.axhspan(
    COLD_HEIGHT,
    COLD_HEIGHT + WALL_THICKNESS,
    color="gray",
    alpha=0.7,
    label="Copper wall"
)

plt.xlabel("Channel length x [m]")
plt.ylabel("Height y [m]")
plt.title(
    "Conjugate Heat Transfer — "
    + ("Counterflow" if COUNTERFLOW else "Parallel Flow")
)
plt.xlim(0, LENGTH)
plt.ylim(0, HEIGHT)
plt.legend()
plt.tight_layout()
plt.show()

# ==============================================================
# 10. TEMPERATURE PROFILES AT SELECTED LOCATIONS
# ==============================================================

positions = [0.25, 0.50, 0.75]

plt.figure(figsize=(8, 5))

for fraction in positions:
    ix = int(fraction * (NX - 1))
    plt.plot(T[:, ix], y, label=f"x/L = {fraction:.2f}")

plt.axhspan(
    COLD_HEIGHT, COLD_HEIGHT + WALL_THICKNESS,
    color="gray", alpha=0.4, label="Copper wall"
)
plt.xlabel("Temperature [deg C]")
plt.ylabel("Height y [m]")
plt.title("Vertical temperature profiles")
plt.grid(True, alpha=0.3)
plt.legend()
plt.tight_layout()
plt.show()

print("\nSimulation summary")
print("Counterflow:", COUNTERFLOW)
print("Converged:", converged)
print("Iterations performed:", it + 1)
print("Final maximum temperature change:", error)
print("Minimum temperature:", np.min(T))
print("Maximum temperature:", np.max(T))