# ================================================================
# 2D FLOW PAST A CIRCULAR CYLINDER
# Immersed Boundary Method (IBM) with Brinkman penalty
# Educational incompressible Navier-Stokes solver
# Google Colab / Python / NumPy / Matplotlib
# ================================================================

import numpy as np
import matplotlib.pyplot as plt

# ------------------------------------------------
# 1. USER-CHANGEABLE PARAMETERS
# ------------------------------------------------

# Geometry (nondimensionalized using cylinder diameter D)
D = 1.0                 # Cylinder diameter
Lx = 25.0               # Computational domain length, in D
Ly = 5.0                # Computational domain height, in D
Cx = Lx / 3.0           # Cylinder center x-coordinate
Cy = Ly / 2.0           # Cylinder center y-coordinate
Cr = D / 2.0            # Cylinder radius

# Grid resolution
nx = 250                # Number of grid points in x
ny = 50                 # Number of grid points in y

# Flow parameters
Re = 100.0              # Reynolds number = U*D/nu
U = 1.0                 # Inlet velocity (reference velocity)
Co = 0.10               # Courant number for time-step selection

# Time integration
nit = 8000              # Number of time steps
pressure_iterations = 40 # Jacobi iterations per time step
alpha_p = 0.3            # Pressure-update relaxation factor

# Immersed boundary parameters
# eta is a penalty time scale; smaller values enforce no-slip
# more strongly but can make the numerical problem stiffer.
eta_factor = 1.0
eta_min = 1.0e-5

# Smooth-mask interface half-width, in grid-cell units.
interface_cells = 1.5

# Plotting controls
plot_every = 500         # Print progress every N steps
make_animation_data = False  # True stores snapshots; uses more memory

# ------------------------------------------------
# 2. GRID AND TIME STEP
# ------------------------------------------------

if nx < 5 or ny < 5:
    raise ValueError("nx and ny must both be at least 5.")
if D <= 0 or Lx <= 0 or Ly <= 0 or U <= 0 or Re <= 0:
    raise ValueError("D, Lx, Ly, U and Re must be positive.")
if nit < 1 or pressure_iterations < 1:
    raise ValueError("nit and pressure_iterations must be positive.")

dx = Lx / nx
dy = Ly / ny

# Explicit convection/diffusion time step.
# The diffusion restriction is also checked.
dt_conv = Co * min(dx, dy) / U
nu = U * D / Re
dt_diff = 0.45 / (
    2.0 * nu * (1.0 / dx**2 + 1.0 / dy**2)
)
dt = min(dt_conv, dt_diff)

# Brinkman penalty time scale.
eta = max(eta_factor * dt, eta_min)

# Coordinates: rows correspond to y; columns correspond to x.
x = np.arange(nx) * dx
y = np.arange(ny) * dy
X, Y = np.meshgrid(x, y)

print("Grid: {} x {}".format(nx, ny))
print("dx = {:.5f}, dy = {:.5f}".format(dx, dy))
print("dt = {:.6f}".format(dt))
print("eta = {:.6f}".format(eta))
print("Re = {:.1f}".format(Re))
print("Final nondimensional time = {:.3f}".format(nit * dt))

if Cx - Cr <= 0 or Cx + Cr >= Lx:
    raise ValueError("Cylinder must fit inside the domain in x.")
if Cy - Cr <= 0 or Cy + Cr >= Ly:
    raise ValueError("Cylinder must fit inside the domain in y.")

# ------------------------------------------------
# 3. IMMERSED BOUNDARY MASK
# ------------------------------------------------

# Signed distance: negative inside the cylinder,
# zero on its surface, positive outside.
distance = np.sqrt((X - Cx)**2 + (Y - Cy)**2) - Cr

# Smooth mask alpha:
# alpha = 1 inside the solid
# alpha = 0 outside the interface
# intermediate values occur across a narrow interface.
eps = interface_cells * max(dx, dy)
alpha = np.clip(0.5 - distance / (2.0 * eps), 0.0, 1.0)

solid_mask = distance < 0.0

plt.figure(figsize=(10, 3))
plt.contourf(X, Y, alpha, levels=30, cmap="gray")
plt.colorbar(label="Immersed boundary mask alpha")
plt.xlabel("x / D")
plt.ylabel("y / D")
plt.title("Smooth immersed-boundary mask")
plt.axis("equal")
plt.tight_layout()
plt.show()

# ------------------------------------------------
# 4. INITIAL CONDITIONS
# ------------------------------------------------

u = np.full((ny, nx), U, dtype=float)
v = np.zeros((ny, nx), dtype=float)
p = np.zeros((ny, nx), dtype=float)

# The initial flow is uniform. The penalty term gradually
# drives the velocity toward zero inside the cylinder.

Cl = np.zeros(nit)
time = np.arange(1, nit + 1) * dt

if make_animation_data:
    snapshots = []

# ------------------------------------------------
# 5. BOUNDARY CONDITIONS
# ------------------------------------------------

def apply_velocity_boundary(u, v):
    # Inlet: uniform flow
    u[:, 0] = U
    v[:, 0] = 0.0

    # Outlet: zero-gradient velocity
    u[:, -1] = u[:, -2]
    v[:, -1] = v[:, -2]

    # Top and bottom: symmetry/slip boundaries
    u[0, :] = u[1, :]
    v[0, :] = 0.0
    u[-1, :] = u[-2, :]
    v[-1, :] = 0.0


def apply_pressure_boundary(pc):
    # Pressure-correction boundary conditions:
    # Neumann at inlet, top and bottom; Dirichlet at outlet.
    pc[:, 0] = pc[:, 1]
    pc[0, :] = pc[1, :]
    pc[-1, :] = pc[-2, :]
    pc[:, -1] = 0.0


# ------------------------------------------------
# 6. PRESSURE-CORRECTION SOLVER
# ------------------------------------------------

def solve_pressure_correction(rhs, pc, iterations):
    """
    Jacobi iteration for:
        Laplacian(pc) = rhs

    The right-hand side is div(u*) / dt.
    """
    pc.fill(0.0)

    for _ in range(iterations):
        apply_pressure_boundary(pc)
        old_pc = pc.copy()

        pc[1:-1, 1:-1] = (
            (old_pc[1:-1, 2:] + old_pc[1:-1, :-2]) * dy**2
            + (old_pc[2:, 1:-1] + old_pc[:-2, 1:-1]) * dx**2
            - dx**2 * dy**2 * rhs[1:-1, 1:-1]
        ) / (2.0 * (dx**2 + dy**2))

    apply_pressure_boundary(pc)
    return pc


# ------------------------------------------------
# 7. MAIN TIME-STEPPING LOOP
# ------------------------------------------------

for n in range(nit):

    apply_velocity_boundary(u, v)

    u_old = u.copy()
    v_old = v.copy()
    p_old = p.copy()

    # Convenient interior slices
    ui = u_old[1:-1, 1:-1]
    vi = v_old[1:-1, 1:-1]
    ai = alpha[1:-1, 1:-1]

    # ------------------------------------------------
    # 7A. MOMENTUM EQUATION: PREDICTOR VELOCITY
    # ------------------------------------------------

    # Upwind convection for u velocity
    conv_u = (
        np.maximum(ui, 0.0) *
        (ui - u_old[1:-1, :-2]) / dx
        + np.minimum(ui, 0.0) *
        (u_old[1:-1, 2:] - ui) / dx
        + np.maximum(vi, 0.0) *
        (ui - u_old[:-2, 1:-1]) / dy
        + np.minimum(vi, 0.0) *
        (u_old[2:, 1:-1] - ui) / dy
    )

    # Upwind convection for v velocity
    conv_v = (
        np.maximum(ui, 0.0) *
        (vi - v_old[1:-1, :-2]) / dx
        + np.minimum(ui, 0.0) *
        (v_old[1:-1, 2:] - vi) / dx
        + np.maximum(vi, 0.0) *
        (vi - v_old[:-2, 1:-1]) / dy
        + np.minimum(vi, 0.0) *
        (v_old[2:, 1:-1] - vi) / dy
    )

    # Laplacian: viscous diffusion
    lap_u = (
        (u_old[1:-1, 2:] - 2.0 * ui
         + u_old[1:-1, :-2]) / dx**2
        + (u_old[2:, 1:-1] - 2.0 * ui
           + u_old[:-2, 1:-1]) / dy**2
    )

    lap_v = (
        (v_old[1:-1, 2:] - 2.0 * vi
         + v_old[1:-1, :-2]) / dx**2
        + (v_old[2:, 1:-1] - 2.0 * vi
           + v_old[:-2, 1:-1]) / dy**2
    )

    # Pressure gradients
    dpdx = (
        p_old[1:-1, 2:] - p_old[1:-1, :-2]
    ) / (2.0 * dx)

    dpdy = (
        p_old[2:, 1:-1] - p_old[:-2, 1:-1]
    ) / (2.0 * dy)

    # Explicit momentum terms
    rhs_u = ui + dt * (
        -conv_u + nu * lap_u - dpdx
    )

    rhs_v = vi + dt * (
        -conv_v + nu * lap_v - dpdy
    )

    # Implicit Brinkman penalty:
    # -alpha*u/eta and -alpha*v/eta
    penalty_denominator = 1.0 + dt * ai / eta

    u[1:-1, 1:-1] = rhs_u / penalty_denominator
    v[1:-1, 1:-1] = rhs_v / penalty_denominator

    apply_velocity_boundary(u, v)

    # ------------------------------------------------
    # 7B. PRESSURE CORRECTION
    # ------------------------------------------------

    # Divergence of predicted velocity
    div = np.zeros((ny, nx), dtype=float)

    div[1:-1, 1:-1] = (
        (u[1:-1, 2:] - u[1:-1, :-2]) / (2.0 * dx)
        + (v[2:, 1:-1] - v[:-2, 1:-1]) / (2.0 * dy)
    )

    pc = solve_pressure_correction(
        div / dt,
        np.zeros_like(p),
        pressure_iterations
    )

    # ------------------------------------------------
    # 7C. VELOCITY AND PRESSURE UPDATE
    # ------------------------------------------------

    # Correct the velocity using the pressure correction.
    u[1:-1, 1:-1] -= (
        dt * (pc[1:-1, 2:] - pc[1:-1, :-2])
        / (2.0 * dx)
        / penalty_denominator
    )

    v[1:-1, 1:-1] -= (
        dt * (pc[2:, 1:-1] - pc[:-2, 1:-1])
        / (2.0 * dy)
        / penalty_denominator
    )

    # Relaxed pressure update
    p = p_old + alpha_p * pc

    apply_velocity_boundary(u, v)

    # ------------------------------------------------
    # 7D. QUALITATIVE LIFT COEFFICIENT
    # ------------------------------------------------

    # Integrated penalty reaction on the solid, per unit span.
    # Density is 1 in this nondimensionalized formulation.
    # This estimate is sensitive to eta, mesh, and mask thickness.
    Fy_body = np.sum(alpha * v) / eta * dx * dy

    # Standard 2D lift coefficient: Fy / (0.5*rho*U^2*D)
    Cl[n] = 2.0 * Fy_body / (U**2 * D)

    if make_animation_data and (n % plot_every == 0):
        snapshots.append((n * dt, u.copy(), v.copy()))

    if n % plot_every == 0:
        speed = np.sqrt(u**2 + v**2)
        div_norm = np.sqrt(np.mean(div[1:-1, 1:-1]**2))
        print(
            "Step {:6d}/{:6d} | t={:8.3f} | "
            "max speed={:.4f} | predictor div RMS={:.3e}".format(
                n + 1, nit, (n + 1) * dt,
                np.max(speed), div_norm
            )
        )

# ------------------------------------------------
# 8. POST-PROCESSING: VELOCITY AND PRESSURE
# ------------------------------------------------

speed = np.sqrt(u**2 + v**2)

fig, axes = plt.subplots(1, 3, figsize=(17, 4))

im0 = axes[0].contourf(X, Y, speed, levels=40, cmap="viridis")
axes[0].add_patch(plt.Circle(
    (Cx, Cy), Cr, color="white", ec="black", zorder=5
))
axes[0].set_title("Velocity magnitude")
axes[0].set_xlabel("x / D")
axes[0].set_ylabel("y / D")
fig.colorbar(im0, ax=axes[0], label="Velocity")

im1 = axes[1].contourf(X, Y, p, levels=40, cmap="coolwarm")
axes[1].add_patch(plt.Circle(
    (Cx, Cy), Cr, color="white", ec="black", zorder=5
))
axes[1].set_title("Pressure field")
axes[1].set_xlabel("x / D")
axes[1].set_ylabel("y / D")
fig.colorbar(im1, ax=axes[1], label="Pressure")

im2 = axes[2].contourf(X, Y, u, levels=40, cmap="viridis")
axes[2].add_patch(plt.Circle(
    (Cx, Cy), Cr, color="white", ec="black", zorder=5
))
axes[2].set_title("Streamwise velocity u")
axes[2].set_xlabel("x / D")
axes[2].set_ylabel("y / D")
fig.colorbar(im2, ax=axes[2], label="u / U")

for ax in axes:
    ax.set_aspect("equal", adjustable="box")

plt.tight_layout()
plt.show()

# ------------------------------------------------
# 9. VORTICITY FIELD
# ------------------------------------------------

# omega_z = dv/dx - du/dy
dvdx = np.gradient(v, dx, axis=1)
dudy = np.gradient(u, dy, axis=0)
vorticity = dvdx - dudy

# Hide the cylinder interior in the plot.
vorticity_plot = vorticity.copy()
vorticity_plot[solid_mask] = np.nan

plt.figure(figsize=(14, 4))
vmax = max(np.nanpercentile(np.abs(vorticity_plot), 98), 1e-8)

plt.contourf(
    X, Y, vorticity_plot,
    levels=np.linspace(-vmax, vmax, 51),
    cmap="seismic", extend="both"
)
plt.colorbar(label="Vorticity (1/time unit)")
plt.gca().add_patch(plt.Circle(
    (Cx, Cy), Cr, color="gray", ec="black"
))
plt.xlabel("x / D")
plt.ylabel("y / D")
plt.title("Vorticity field at t = {:.3f}".format(nit * dt))
plt.axis("equal")
plt.tight_layout()
plt.show()

# ------------------------------------------------
# 10. LIFT COEFFICIENT HISTORY
# ------------------------------------------------

plt.figure(figsize=(10, 3.5))
plt.plot(time, Cl, linewidth=0.8)
plt.xlabel("Dimensionless time t U / D")
plt.ylabel("Lift coefficient CL")
plt.title("Qualitative lift coefficient history")
plt.grid(True, alpha=0.3)
plt.tight_layout()
plt.show()

# ------------------------------------------------
# 11. FFT AND STROUHAL NUMBER
# ------------------------------------------------

# Use the last half of the lift signal to reduce startup effects.
start = nit // 2
cl_signal = Cl[start:].copy()
cl_signal -= np.mean(cl_signal)

# Apply a Hann window to reduce spectral leakage.
window = np.hanning(len(cl_signal))
signal_windowed = cl_signal * window

if np.max(np.abs(cl_signal)) > 1e-6 and len(cl_signal) >= 8:
    # Zero padding improves display interpolation, not true resolution.
    nfft = 8 * len(signal_windowed)

    spectrum = np.abs(np.fft.rfft(signal_windowed, n=nfft))
    frequencies = np.fft.rfftfreq(nfft, d=dt)

    # Exclude the zero-frequency component.
    if len(frequencies) > 1:
        peak_index = 1 + np.argmax(spectrum[1:])
        f_shed = frequencies[peak_index]
        St = f_shed * D / U

        print("\n========== RESULTS ==========")
        print("Maximum |CL| in last half: {:.6f}".format(
            np.max(np.abs(cl_signal))
        ))
        print("Estimated shedding frequency: {:.5f}".format(f_shed))
        print("Estimated Strouhal number: {:.5f}".format(St))
        print("Reference for Re=100: approximately 0.16-0.17")
        print("Compare only after numerical convergence checks.")

        plt.figure(figsize=(9, 3.5))
        plt.plot(frequencies, spectrum)
        plt.axvline(f_shed, linestyle="--",
                    label="Peak = {:.4f}".format(f_shed))
        plt.xlim(0, min(1.0, frequencies[-1]))
        plt.xlabel("Frequency (U / D)")
        plt.ylabel("FFT amplitude (arbitrary units)")
        plt.title("Lift-coefficient frequency spectrum")
        plt.legend()
        plt.grid(True, alpha=0.3)
        plt.tight_layout()
        plt.show()
else:
    print(
        "\nLift signal is nearly flat. Do not report a Strouhal "
        "number until sustained periodic shedding is established."
    )

print("\nSimulation finished.")