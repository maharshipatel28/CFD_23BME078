import numpy as np
import matplotlib.pyplot as plt
from scipy.ndimage import gaussian_filter

# ============================================================
# RAYLEIGH-TAYLOR INSTABILITY
# Educational interface-evolution model
# ============================================================

# 1. PARAMETERS
nx, ny = 100, 200
Lx, Ly = 1.0, 2.0

dx = Lx / nx
dy = Ly / ny

rho_light = 1.0
rho_heavy = 2.0
g = 9.81
nu = 0.001

A0 = 0.04
t_end = 1.5
dt = 0.001

# 2. GRID
x = (np.arange(nx) + 0.5) * dx
y = (np.arange(ny) + 0.5) * dy

X, Y = np.meshgrid(x, y)

# 3. INITIAL INTERFACE
interface = Ly / 2 + A0 * np.cos(2 * np.pi * x / Lx)

# Heavy-fluid volume fraction
alpha = np.clip(
    (Y - interface[None, :] + dy / 2) / dy,
    0.0,
    1.0
)

# 4. ATWOOD NUMBER
At = (rho_heavy - rho_light) / (rho_heavy + rho_light)

# 5. INITIAL CONDITIONS AND STORAGE
snap_times = [0.0, 0.5, 1.0, 1.5]
snapshots = [(0.0, alpha.copy())]

initial_mass = np.sum(alpha) * dx * dy

# Interface displacement amplitude
amplitude = A0

# Approximate linear RTI growth rate for the initial mode.
# This is an educational model, not a Navier-Stokes solution.
k = 2 * np.pi / Lx
growth_rate = np.sqrt(max(At * g * k - nu**2 * k**4, 0.0))

# 6. TIME INTEGRATION
t = 0.0
steps = 0

while t < t_end - 1e-12:

    step = min(dt, t_end - t)
    t_next = t + step

    # Approximate growth of the initial interface disturbance
    amplitude = A0 * np.cosh(growth_rate * t_next)

    # Prevent the illustrative interface from exceeding the domain
    amplitude = min(amplitude, 0.40 * Ly)

    interface_now = (
        Ly / 2
        + amplitude * np.cos(2 * np.pi * x / Lx)
    )

    # Construct a bounded volume-fraction field
    alpha = np.clip(
        (Y - interface_now[None, :] + dy / 2) / dy,
        0.0,
        1.0
    )

    t = t_next
    steps += 1

    # Save requested snapshots
    while (
        len(snapshots) < len(snap_times)
        and t >= snap_times[len(snapshots)] - 1e-12
    ):
        snapshots.append((t, alpha.copy()))

# 7. FINAL DIAGNOSTICS
final_mass = np.sum(alpha) * dx * dy

relative_mass_error = (
    abs(final_mass - initial_mass)
    / max(abs(initial_mass), 1e-12)
)

print("\n========== SIMULATION RESULTS ==========")
print(f"Grid size              : {nx} x {ny}")
print(f"Grid spacing dx        : {dx:.6f} m")
print(f"Grid spacing dy        : {dy:.6f} m")
print(f"Time steps             : {steps}")
print(f"Final time             : {t:.4f} s")
print(f"Atwood number          : {At:.6f}")
print(f"Approx. growth rate    : {growth_rate:.6f} 1/s")
print(f"Initial heavy-fluid area: {initial_mass:.8f} m^2")
print(f"Final heavy-fluid area  : {final_mass:.8f} m^2")
print(f"Relative mass error     : {relative_mass_error:.6e}")
print(f"Volume fraction range   : [{alpha.min():.4f}, {alpha.max():.4f}]")
print("========================================")

# 8. PLOT RESULTS
fig, axes = plt.subplots(
    1,
    len(snapshots),
    figsize=(15, 4.5),
    sharex=True,
    sharey=True
)

for ax, (time_value, field) in zip(axes, snapshots):

    im = ax.imshow(
        field,
        origin="lower",
        extent=[0, Lx, 0, Ly],
        aspect="auto",
        cmap="Blues",
        vmin=0,
        vmax=1
    )

    ax.contour(
        x,
        y,
        field,
        levels=[0.5],
        colors="black",
        linewidths=1
    )

    ax.set_title(f"t = {time_value:.2f} s")
    ax.set_xlabel("x (m)")

axes[0].set_ylabel("y (m)")

fig.suptitle(
    "Rayleigh-Taylor Instability: Interface Evolution",
    fontsize=14
)

fig.colorbar(
    im,
    ax=axes,
    label="Heavy-fluid volume fraction",
    shrink=0.85
)

plt.tight_layout()
plt.savefig(
    "experiment_4_rti_output.png",
    dpi=200,
    bbox_inches="tight"
)
plt.show()