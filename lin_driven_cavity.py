# ============================================================
# 9. EXTRACT CENTRELINE PROFILES
# ============================================================

ix = np.argmin(np.abs(x - LENGTH / 2.0))
iy = np.argmin(np.abs(y - LENGTH / 2.0))

u_center = u_vel[:, ix]
v_center = v_vel[iy, :]

u_rmse = np.sqrt(np.mean(
    (np.interp(ghia_y, y, u_center / LID_SPEED) - ghia_u)**2
))

v_rmse = np.sqrt(np.mean(
    (np.interp(ghia_x, x, v_center / LID_SPEED) - ghia_v)**2
))

print(f"Vertical centreline RMSE   = {u_rmse:.6f}")
print(f"Horizontal centreline RMSE = {v_rmse:.6f}")


# ============================================================
# 10. CREATE THE THREE-PANEL FIGURE
# ============================================================

fig, axes = plt.subplots(
    1, 3,
    figsize=(18, 5.5)
)

